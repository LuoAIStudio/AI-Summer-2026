#以下学习字典,可以用来描述一个事物，比较灵活，它与列表最大的区别是是否有序
小明={"name":"小明",
    "age":18,
    "height":1.73}#把每一个键值对看成一个整体
print(小明["age"])#取值
#key一定要加",因为它是str，不然会被认为是一个变量
小明["hansun"]="ture"#增加一个key与相对应的数据
小明["name"]="小小明"#如果存在，则变为了修改
小明.pop("age")#做一个删除
print(小明)
print(len(小明))#统计键值对的数量
#以下来学合并，在新键一个键值对（update）
张三={"name":"张三",
    "age":19,
    "height":1.76}
小明.update(张三)#已经存在的键值对则会被直接覆盖
print(小明)
小明.clear()
print(小明)#全部清空
#以下来学习循环遍历,因为数据类型基本上不相同，所以一般都不会使用循环遍历
for k in 张三:
    print("%s——%s"%(k,张三[k]))

#以下学习元组（与列表相似，但元素不能修改），所以基本上不会使用空元组，它也可以保护数据安全
tuple1=(23,"小明",12.3,12.3)
print(type(tuple1))#明确变量的类型
print(tuple1[2])#用中括号进行索引
tuple2=(5,)#定义一个元素的元组，需加一个逗号来明确元素的类型，不能像int（）来改变变量类型,但在元组与列表可以相互修改
print(type(tuple2))
#以下学习元组的操作(count,index)
print(tuple1.index(23))#取索引是明确一个元素在元组中的位置
print(tuple1.count(12.3))#这个是明确一个元素在元组中出现的次数
print(len(tuple1))#明确元组中元素
#以下学习元组的循环遍历（for）
for my_infor in tuple1:
    print(my_infor)
#每一个元素执行一个相同的代码
#格式化字符串后面多个变量而使用的括号就是元组
name=("霞姐","小姐","小明")
print("这个班的学生名字有:%s,%s,%s"%name)#格式化字符串要一一对应
#以下学习元组与列表之间的转换，就像数据类型之间的修改（int()）
name1=["张三","王五"]
name2=tuple(name1)
print(type(name2))

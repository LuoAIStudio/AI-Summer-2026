#以下学习字符串
str1='我的外号是"小杰"'#大部分的时候都是用是用双引号，如果想在文字里加双引号,则最外面使用单引号
print(str1)
print(str1[5])#双引号也会被标一个序号，同理空格也算
str2="hallo"
for char in str2:
    print(char)#字符串的循环遍历
print(len(str2))
print(str2.count("ll"))#统计子字符串个数，如果没有则会显示0
print(str2.index("a"))#还是用index进行索引


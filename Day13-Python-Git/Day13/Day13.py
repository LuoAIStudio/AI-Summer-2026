#以下学习变量的引用
a=1
print(id(a))
print(id(1))#id函数可以查询地址，id函数只注重数据在哪里，并不注意变量的位置
#数据都是保存在内存当中的一个位置，叫做地址，而变量就是访问这个地址的，叫做引用
def test(num):
    print("在函数内部%d对应的内存地址是%d"%(num,id(num)))
    resut="hello"
    print("%s的内存地址是%d"%(resut,id(resut)))
    return resut
a=1
print("a的引用数据地址是在%d"%id(a))
c=test(a)#用c这个变量来接收函数的返回值，也是返回数据的地址，没有接收的话也不会出错
#实参传递的是数据地址，让形参的num变量引用这个地址
print("%s的内存地址是%d"%(c,id(c)))
#可变类型的话目前只有列表与字典
b=[1,2,3,4]
print(id(b))
b.append(5)
print(b)

#用方法来修改列表是不会影响列表，字典在内存之间的位置
b=[1,2,3,4,5]
print(id(b))
#如果用赋值的话即使一样的数据也会影响变量的引用
#字典的key是可以以字符串，数字，元组组成，列表与字典的可变数据是不行的
print(hash("hello"))
print(hash(1))
#哈希函数是输入一个数据（不可变数据）就会反馈一个特征码，就像指纹那样具有唯一性
#在字典当中，会对key进行哈希来保存数据，这便是字典的底层处理，所以key不能是可变数据，值的话是可以随意数据的
